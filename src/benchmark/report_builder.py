    def _append_detailed_rank_table(
        self,
        lines: list[str],
        per_rank_results: list[Any],
    ) -> None:
        """
        Add a wider per-rank metrics table for quick result inspection.
        """
        lines.append("## Detailed Per-Rank Metrics")
        lines.append("")
        lines.append(
            "| Rank | Role | Active | Messages | Failed | Bytes | Duration (sec) | "
            "Throughput (msg/s) | Throughput (MiB/s) | Readiness Assignment | "
            "Benchmark Assignment Max | Final Assignment |"
        )
        lines.append("|---:|---|---|---:|---:|---:|---:|---:|---:|---|---:|---|")

        for result in per_rank_results:
            if not isinstance(result, dict):
                continue
            metrics = result.get("metrics", {})
            if not isinstance(metrics, dict):
                metrics = {}
            role = str(result.get("role", "unknown"))
            if role == "producer":
                messages = metrics.get("messages_delivered", 0)
                failed = metrics.get("messages_failed", 0)
                bytes_count = metrics.get("bytes_delivered", 0)
            elif role == "consumer":
                messages = metrics.get("messages_received", 0)
                failed = metrics.get("messages_failed", 0)
                bytes_count = metrics.get("bytes_received", 0)
            else:
                messages = failed = bytes_count = 0

            assignment = ""
            benchmark_assignment = ""
            final_assignment = ""
            if role == "consumer":
                assignment = "yes" if metrics.get("readiness_assignment_received") else "no"
                benchmark_assignment = metrics.get("benchmark_assignment_count_max", "")
                final_assignment = "yes" if metrics.get("final_assignment_received") else "no"

            lines.append(
                "| {rank} | {role} | {active} | {messages} | {failed} | {bytes_count} | {duration:.3f} | {throughput:.3f} | {mb_rate:.3f} | {assignment} | {benchmark_assignment} | {final_assignment} |".format(
                    rank=result.get("rank", "unknown"),
                    role=_pipe_safe(role),
                    active="yes" if result.get("active", True) else "no",
                    messages=messages,
                    failed=failed,
                    bytes_count=bytes_count,
                    duration=_as_float(metrics.get("duration_sec")),
                    throughput=_as_float(metrics.get("throughput_msgs_per_sec")),
                    mb_rate=_metric_mebibytes_per_sec(metrics),
                    assignment=assignment,
                    benchmark_assignment=benchmark_assignment,
                    final_assignment=final_assignment,
                )
            )
        lines.append("")

