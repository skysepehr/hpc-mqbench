        lines.append(
            "- **Consumer Throughput (bytes/s):** "
            f"{consumers.get('throughput_bytes_per_sec', 0.0):.3f}"
        )
        lines.append(
            "- **Consumer Throughput (MiB/s):** "
            f"{_metric_mebibytes_per_sec(consumers):.3f}"
        )
