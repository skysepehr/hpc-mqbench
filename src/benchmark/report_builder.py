def _write_svg_bar_chart(
    output_path: Path,
    title: str,
    unit: str,
    description: str,
    values: list[tuple[str, float]],
) -> None:
    """
    Write a presentation-quality horizontal bar chart using only stdlib SVG.
    """
    width = 1100
    row_height = 58
    top_margin = 112
    left_margin = 270
    right_margin = 180
    bottom_margin = 78
    chart_width = width - left_margin - right_margin
    height = top_margin + bottom_margin + row_height * len(values)
    max_value = max((value for _, value in values), default=0.0)
    if max_value <= 0:
        max_value = 1.0

    palette = ["#1769aa", "#c2410c", "#168a5c", "#7c3aed", "#b45309"]
    escaped_title = html.escape(title)
    escaped_description = html.escape(description)
    escaped_unit = html.escape(unit)
    axis_y = top_margin + row_height * len(values) + 8
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-label="{escaped_title}">',
        "<style>",
        ".title{font:700 27px Arial,sans-serif;fill:#17202a}",
        ".subtitle{font:14px Arial,sans-serif;fill:#52606d}",
        ".axis{font:12px Arial,sans-serif;fill:#607080}",
        ".label{font:15px Arial,sans-serif;fill:#24384c}",
        ".value{font:700 14px Arial,sans-serif;fill:#17202a}",
        ".grid{stroke:#dfe7f0;stroke-width:1}",
        ".track{fill:#eef3f8}",
        "</style>",
        '<rect width="100%" height="100%" fill="#ffffff"/>',
        '<rect x="12" y="12" width="{w}" height="{h}" rx="14" fill="#ffffff" stroke="#d8e0ea"/>'.format(
            w=width - 24,
            h=height - 24,
        ),
        f'<text class="title" x="34" y="44">{escaped_title}</text>',
        f'<text class="subtitle" x="34" y="70">{escaped_description}</text>',
        f'<text class="subtitle" x="34" y="92">Unit: {escaped_unit}. Maximum displayed value: {html.escape(_format_number(max_value))}.</text>',
    ]

    for tick in range(5):
        fraction = tick / 4
        x = left_margin + chart_width * fraction
        tick_value = max_value * fraction
        lines.extend(
            [
                f'<line class="grid" x1="{x:.2f}" y1="{top_margin - 10}" x2="{x:.2f}" y2="{axis_y}"/>',
                f'<text class="axis" x="{x:.2f}" y="{axis_y + 24}" text-anchor="middle">{html.escape(_format_number(tick_value))}</text>',
            ]
        )

    for index, (label, value) in enumerate(values):
        y = top_margin + index * row_height
        bar_width = int((value / max_value) * chart_width) if value > 0 else 0
        color = palette[index % len(palette)]
        lines.extend(
            [
                f'<text class="label" x="34" y="{y + 32}">{html.escape(label)}</text>',
                f'<rect class="track" x="{left_margin}" y="{y + 13}" width="{chart_width}" height="28" rx="6"/>',
                f'<rect x="{left_margin}" y="{y + 13}" width="{bar_width}" height="28" rx="6" fill="{color}"/>',
                f'<text class="value" x="{left_margin + chart_width + 18}" y="{y + 32}">{html.escape(_format_number(value))}</text>',
            ]
        )

    lines.append(
        f'<text class="axis" x="{left_margin + chart_width / 2:.2f}" y="{height - 28}" text-anchor="middle">{escaped_unit}</text>'
    )
    lines.append("</svg>")
    output_path.write_text("\n".join(lines), encoding="utf-8")


def _normalize_report_mode(value: str) -> str:
    mode = str(value or "full").strip().lower()
    if mode not in {"full", "light", "machine"}:
        raise ValueError(
            "BENCHMARK_REPORT_MODE must be 'full', 'light', or 'machine', "
            f"got: {value!r}"
        )
    return mode


def _as_float(value: Any) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def _load_events(path: Path) -> list[Any]:
    if not path.is_file():
        return []
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return []
    if isinstance(data, dict):
        events = data.get("events", [])
        return events if isinstance(events, list) else []
    return []


def _dict(value: Any) -> dict[str, Any]:
    return value if isinstance(value, dict) else {}


def _list(value: Any) -> list[Any]:
    return value if isinstance(value, list) else []


def _metric_mebibytes_per_sec(metrics: dict[str, Any]) -> float:
    """Read binary MiB/s when present, otherwise derive it from bytes/s."""
    explicit_value = _as_float(metrics.get("throughput_mebibytes_per_sec"))
    if explicit_value > 0:
        return explicit_value
    return _as_float(metrics.get("throughput_bytes_per_sec")) / 1_048_576


def _send_attempt_mebibytes_per_sec(metrics: dict[str, Any]) -> float:
    explicit_value = _as_float(
        metrics.get("send_attempt_throughput_mebibytes_per_sec")
    )
    if explicit_value > 0:
        return explicit_value
    return (
        _as_float(metrics.get("send_attempt_throughput_bytes_per_sec"))
        / 1_048_576
    )


def _format_number(value: float) -> str:
    if abs(value) >= 1000:
        return f"{value:,.0f}"
    if value == int(value):
        return str(int(value))
    return f"{value:.3f}"


def _format_counts(value: Any) -> str:
    if not isinstance(value, dict) or not value:
        return "none"
    items = sorted(
        ((str(key), int(count)) for key, count in value.items()),
        key=lambda item: (-item[1], item[0]),
    )
    return ", ".join(f"{key}: {count}" for key, count in items[:8])


def _pipe_safe(value: Any) -> str:
    return str(value).replace("|", "\\|")
