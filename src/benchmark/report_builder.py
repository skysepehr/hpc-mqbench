        if isinstance(egress_prefill, dict) and egress_prefill.get("enabled"):
            self._append_egress_prefill_section(lines, egress_prefill)

        # Per-rank summary
        lines.append("## Per-Rank Results")
        lines.append("")
        lines.append("| Rank | Role | Notes |")
        lines.append("|---:|---|---|")

